import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
await p.goto("http://localhost:8323/preview.html", { waitUntil: "load" }); await p.waitForTimeout(1500);
await p.screenshot({ path: out + "/r2-top.png" });
await p.evaluate(() => document.querySelector("#s-hero").scrollIntoView()); await p.waitForTimeout(5000);
await p.screenshot({ path: out + "/r2-hero.png" });
await p.click("#ok-hero"); await p.waitForTimeout(300);
const st = await p.evaluate(() => ({ prog: document.querySelector("#prog-txt").textContent, chip: document.querySelector("#chip-hero").textContent, sum: document.querySelector("#summary-pre").textContent.split("\n").slice(0, 3).join(" | "), frame: !!document.querySelector("#stage-hero iframe.is-ready") }));
const h = await b.newPage({ viewport: { width: 1200, height: 900 } });
await h.goto("http://localhost:8323/home.html", { waitUntil: "load" }); await h.waitForTimeout(1500);
const home = await h.evaluate(() => ({ slots: document.querySelectorAll(".km-slot").length, zoom: getComputedStyle(document.body).getPropertyValue("--page-zoom"), sw: document.documentElement.scrollWidth }));
const m = await b.newPage({ viewport: { width: 390, height: 844 } });
await m.goto("http://localhost:8323/preview.html", { waitUntil: "load" }); await m.waitForTimeout(800);
const mob = await m.evaluate(() => document.documentElement.scrollWidth);
console.log(JSON.stringify({ st, home, mob, errs }));
await b.close();
